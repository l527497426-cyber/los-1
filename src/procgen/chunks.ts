import type { ChunkTemplate, TileId } from "./types";

// 工具：从字符串行画 chunk
// "." 空 / "#" 石 / "^" 尖刺 / "<" 入口标记 / ">" 出口标记（仅注释作用）
function parse(
  id: string,
  rows: string[],
  meta: Omit<ChunkTemplate, "id" | "terrain" | "widthTiles" | "heightTiles" | "entryY" | "exitY"> & {
    entryY: number;
    exitY: number;
  },
): ChunkTemplate {
  const heightTiles = rows.length;
  const widthTiles = Math.max(...rows.map((r) => r.length));
  const terrain: TileId[][] = [];
  const anchors: { x: number; y: number }[] = [];
  for (let y = 0; y < heightTiles; y++) {
    const row: TileId[] = [];
    const r = rows[y] ?? "";
    for (let x = 0; x < widthTiles; x++) {
      const c = r[x] ?? ".";
      if (c === "#") row.push(1);
      else if (c === "^") row.push(2);
      else if (c === "o") {
        row.push(0);
        anchors.push({ x, y });        // "o" = 悬浮 Bash 锚点
      } else row.push(0);
    }
    terrain.push(row);
  }
  return {
    id,
    widthTiles,
    heightTiles,
    terrain,
    ...meta,
    bashAnchors: anchors.length > 0 ? anchors : meta.bashAnchors,
  };
}

